# -*- coding: utf-8 -*-
"""Xiaohongshu public-page comment capture for VideoToGPT.

Observes JSON responses generated by the logged-in Edge page itself. No
signature creation, endpoint replay, login bypass or cookie export. Completion
is measured against observed page cursors and reported reply counts, and is
never silently promoted to 'all comments' when unverified.
"""
from __future__ import annotations

import collections
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import re
import threading
import time
import urllib.parse

# Share the dedicated profile with the previous 0.2.1 / 0.2.2 collector.
PROFILE = Path(os.environ.get('LOCALAPPDATA', str(Path.home()))) / 'VideoToGPT' / 'XHS_Edge_Profile'


def note_id_from_url(url: str) -> str | None:
    parts = urllib.parse.urlsplit(url)
    m = re.search(r'/(?:discovery/item|explore)/([a-z0-9]{24})(?:/|$)', parts.path, re.I)
    return m.group(1).lower() if m else None


def nonnegative_int(value) -> int:
    try:
        return max(0, int(value))
    except (ValueError, TypeError):
        # Platforms sometimes display a human-readable count such as "10+".
        m = re.match(r"\s*(\d+)", str(value))
        return int(m.group(1)) if m else 0


def normalize_comment(c: dict, reply: bool = False, parent: str = '') -> dict:
    user = c.get('user_info') or c.get('user') or {}
    if not isinstance(user, dict):
        user = {}
    content = str(c.get('content') or c.get('text') or '').strip()
    cid = str(c.get('id') or c.get('comment_id') or '').strip()
    if not cid:
        token = f'{c.get("create_time")}|{user.get("user_id")}|{content}|{parent}'
        cid = 'generated_' + hashlib.sha256(token.encode('utf-8')).hexdigest()[:20]
    return {
        'id': cid,
        'parent_id': str(c.get('root_comment_id') or parent or ''),
        'is_reply': bool(reply or c.get('root_comment_id')),
        'author': str(user.get('nickname') or user.get('nick_name') or ''),
        'content': content,
        'created_at': c.get('create_time') or c.get('time'),
        'like_count': c.get('like_count') or '0',
        'child_reply_count': nonnegative_int(c.get('sub_comment_count')), 
    }


def parse_comment_response(request_url: str, payload: object, expected_note_id: str | None):
    """Return (rows, category, metadata) from browser-observed response."""
    parts = urllib.parse.urlsplit(request_url)
    path = parts.path
    is_root = path.endswith('/comment/page')
    is_sub = path.endswith('/comment/sub/page')
    if not (is_root or is_sub) or not isinstance(payload, dict):
        return None
    params = urllib.parse.parse_qs(parts.query)
    response_id = (params.get('note_id') or [None])[0]
    if expected_note_id and response_id and expected_note_id.lower() != response_id.lower():
        return None
    data = payload.get('data') or {}
    if not isinstance(data, dict):
        return None
    root_id = str((params.get('root_comment_id') or [None])[0] or data.get('root_comment_id') or '')
    meta = {
        'success': payload.get('success', True),
        'has_more': data.get('has_more'),
        'cursor': data.get('cursor') or data.get('next_cursor'),
        'root_id': root_id,
    }
    rows = []
    for c in data.get('comments') or []:
        if not isinstance(c, dict):
            continue
        rows.append(normalize_comment(c, reply=is_sub, parent=root_id))
        for sub in c.get('sub_comments') or []:
            if isinstance(sub, dict):
                rows.append(normalize_comment(sub, reply=True, parent=str(c.get('id') or '')))
    return rows, ('root' if is_root else 'sub'), meta


def completeness(records: list[dict], observed_pages: dict, ended_automatically: bool,
                 stop_reason: str) -> dict:
    roots = [r for r in records if not r['is_reply']]
    # Sometimes a subcomment is received before its parent. Counting those
    # does not establish that main-page pagination has finished.
    reply_by_parent = collections.Counter(r['parent_id'] for r in records if r['is_reply'])
    missing = {
        r['id']: {'author': r['author'], 'reported': r['child_reply_count'],
                  'captured': reply_by_parent[r['id']]}
        for r in roots if r['child_reply_count'] > reply_by_parent[r['id']]
    }
    root_pages = observed_pages.get('root', [])
    root_end = any(p.get('has_more') is False for p in root_pages)
    root_seen = len(root_pages) > 0
    sub_observed = observed_pages.get('sub', {})
    root_complete = root_seen and root_end
    # Not all platforms reliably disclose total visible comment count; 'complete'
    # is only scoped to the browser's observed pagination, not the whole platform.
    observed_complete = root_complete and not missing and ended_automatically
    return {
        'status': '本次浏览会话分页结束（不保证平台全量）' if observed_complete else '部分采集或无法验证完整性',
        'root_pages_seen': len(root_pages),
        'root_has_more_last': root_pages[-1].get('has_more') if root_pages else None,
        'root_end_observed': root_end,
        'reply_pages_seen': sum(len(pages) for pages in sub_observed.values()),
        'captured_root_comments': len(roots),
        'captured_replies': len(records) - len(roots),
        'reported_reply_gaps': missing,
        'auto_end': ended_automatically,
        'stop_reason': stop_reason,
        'note': '只依据当前浏览器实际返回的分页和回复数；平台可能隐藏、筛选或限制评论，不能保证取得所有历史评论。',
    }


def report_stats(records: list[dict], coverage: dict) -> str:
    cleaned = [re.sub(r'\s+', '', x['content']).lower() for x in records]
    repeated = [(t, n) for t, n in collections.Counter(cleaned).most_common() if t and n > 1]
    lines = [
        '小红书评论采集报告（不是机器人鉴定）',
        '完整性状态：' + coverage['status'],
        f'实际采集评论及回复：{len(records)}',
        f'一级评论：{coverage["captured_root_comments"]}；回复：{coverage["captured_replies"]}',
        f'观察到一级评论分页：{coverage["root_pages_seen"]} 次；是否观察到结束：{coverage["root_end_observed"]}',
        f'观察到回复分页：{coverage["reply_pages_seen"]} 次',
        f'已知未补齐回复的一级评论：{len(coverage["reported_reply_gaps"])} 条',
        '停止原因：' + coverage['stop_reason'],
        '', '重复文本示例（只能作为异常线索）：'
    ]
    for s, n in repeated[:20]:
        lines.append(f'重复{n}次：{s[:160]}')
    lines.extend(['', coverage['note']])
    return '\n'.join(lines) + '\n'


def render_comments(records: list[dict]) -> str:
    lines = ['小红书实际采集到的评论（按首次加载顺序；并非全量保证）', '']
    for index, r in enumerate(records, 1):
        ts = r['created_at']
        if ts is not None:
            try:
                num = float(ts)
                if num > 1e11: num /= 1000
                ts = dt.datetime.fromtimestamp(num).astimezone().isoformat(timespec='seconds')
            except (ValueError, TypeError, OverflowError, OSError):
                pass
        lines.extend([
            f'[{index}] {"回复" if r["is_reply"] else "一级评论"} | {r["author"]} | 点赞 {r["like_count"]} | {ts or "时间不详"}',
            f'ID: {r["id"]}' + (f'; 上级: {r["parent_id"]}' if r['parent_id'] else ''),
            r['content'] or '（无文字）', ''
        ])
    return '\n'.join(lines) + '\n'


def save_result(url: str, store: dict, observed: dict, auto_end: bool, reason: str,
                logs: list[str], target_dir: Path):
    target_dir.mkdir(parents=True, exist_ok=True)
    rows = list(store.values())
    coverage = completeness(rows, observed, auto_end, reason)
    (target_dir / 'comments.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding='utf-8-sig')
    (target_dir / 'comments.txt').write_text(render_comments(rows), encoding='utf-8-sig')
    (target_dir / 'comment_stats.txt').write_text(report_stats(rows, coverage), encoding='utf-8-sig')
    (target_dir / 'comment_coverage.json').write_text(json.dumps(coverage, ensure_ascii=False, indent=2), encoding='utf-8-sig')
    (target_dir / 'README_评论说明.txt').write_text(
        '此文件来自同一条小红书笔记的浏览器评论采集。\n'
        + coverage['note'] + '\n不保存账户口令、Cookie或本地浏览器资料。\n'
        + '\n'.join(logs[-35:]), encoding='utf-8-sig')
    return coverage


# Work with both visible scroll containers and scrollable page. Never send
# site-specific requests directly or fabricate pagination cursors.
LOGIN_DIALOG_JS = r"""() => {
  const selectors = ['[class*="login-modal"]','[class*="login-container"]',
    '[class*="login-wrapper"]','[class*="login-panel"]',
    '[class*="qrcode"]','[class*="qr-code"]'];
  for (const selector of selectors) {
    for (const el of document.querySelectorAll(selector)) {
      const r=el.getBoundingClientRect();
      const css=getComputedStyle(el);
      if (r.width < 100 || r.height < 100 || css.display === 'none' || css.visibility === 'hidden') continue;
      const msg=(el.innerText||el.textContent||'').slice(0,1200);
      if (/扫码登录|登录小红书|手机号登录|请先登录|二维码登录|扫码/gi.test(msg)) return true;
    }
  }
  return false;
}"""

SCROLL_JS = r"""() => {
  const nodes = [...document.querySelectorAll('*')].filter(el => {
    const h = el.scrollHeight - el.clientHeight;
    if (h < 110 || el.clientHeight < 140) return false;
    const cl = String(el.className || '').toLowerCase();
    return /comment|interaction|detail|note|scroller/.test(cl);
  });
  nodes.sort((a,b) => (b.scrollHeight-b.clientHeight)-(a.scrollHeight-a.clientHeight));
  if (nodes.length) {
    const x=nodes[0]; x.scrollTop=Math.min(x.scrollHeight,x.scrollTop+Math.max(350,x.clientHeight*.85));
  } else {
    window.scrollBy(0,Math.max(400,window.innerHeight*.75));
  }
}"""


def collect(url: str, stop: threading.Event, auto_scroll: threading.Event, send,
            target_dir: Path | None = None, *, max_seconds: int = 360) -> None:
    """Scan comments automatically using the user's dedicated logged-in Edge profile.

    `stop` enables early manual stop, auto_scroll=enabled starts full UI scrolling.
    On site auth/rate-limit interruptions, report partial capture, not success.
    """
    if target_dir is None:
        raise ValueError('本版本评论采集必须与原帖共用同一个任务目录')
    store: dict[str, dict] = {}
    observed: dict = {'root': [], 'sub': {}}
    logs: list[str] = []
    context = None
    root_ended_at = None
    started_at = time.monotonic()
    last_count_at = started_at
    last_page_at = started_at
    stopped_reason = '未知'
    auto_end = False
    observed_failures = 0
    reply_button_clicks = 0

    def log(s):
        logs.append(str(s))
        send(('log', str(s)))

    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        send(('error', '未安装 Playwright。请运行安装或构建脚本。'))
        return
    try:
        with sync_playwright() as p:
            PROFILE.mkdir(parents=True, exist_ok=True)
            log('打开 Edge 专用配置。已经成功登录过同一配置的账号会尽量保持登录。')
            context = p.chromium.launch_persistent_context(
                user_data_dir=str(PROFILE), channel='msedge', headless=False,
                viewport={'width': 1230, 'height': 900}, args=['--no-first-run'])
            page = context.pages[0] if context.pages else context.new_page()
            target = {'note_id': note_id_from_url(url)}

            def on_response(resp):
                nonlocal last_count_at, last_page_at, root_ended_at, observed_failures
                try:
                    if not (resp.url.split('?')[0].endswith('/comment/page') or
                            resp.url.split('?')[0].endswith('/comment/sub/page')):
                        return
                    if resp.status >= 400:
                        observed_failures += 1
                        log(f'评论页面请求 HTTP {resp.status}，可能需要登录或已触发访问限制')
                        return
                    data = parse_comment_response(resp.url, resp.json(), target['note_id'])
                    if data is None:
                        return
                    rows, typ, meta = data
                    if meta['success'] is False:
                        observed_failures += 1
                        log('页面评论响应提示失败，不能保证完整')
                        return
                    now = time.monotonic()
                    last_page_at = now
                    if typ == 'root':
                        observed['root'].append(meta)
                        if meta['has_more'] is False:
                            root_ended_at = now
                    else:
                        root_id = meta['root_id'] or '__unknown__'
                        observed['sub'].setdefault(root_id, []).append(meta)
                    before = len(store)
                    for r in rows:
                        store[r['id']] = r
                    if len(store) > before:
                        last_count_at = now
                        send(('count', len(store)))
                except Exception as e:
                    log('评论接口数据解析失败：' + str(type(e).__name__))

            page.on('response', on_response)
            try:
                page.goto(url, wait_until='domcontentloaded', timeout=60000)
                target['note_id'] = note_id_from_url(page.url) or target['note_id']
            except Exception as exc:
                log('初次打开页面失败，可在 Edge 手动登录后刷新：' + str(type(exc).__name__))
            log('仅采集此浏览器会话可见评论；遇到登录或验证会停止，不会要求反复扫码。')
            next_scroll = time.monotonic() + 2
            next_reply = time.monotonic() + 4
            login_prompt_since = None
            # Will stop when observed pagination end & all advertised replies
            # are present and page has been quiet. Else wait up to budget.
            while True:
                now = time.monotonic()
                if stop.is_set():
                    stopped_reason = '用户手动提前结束'
                    break
                if now - started_at >= max_seconds:
                    stopped_reason = f'达到采集时限（{max_seconds}秒），保留部分数据'
                    break
                try:
                    page.wait_for_timeout(350)
                    # If in a different tab, read currently opened URL but do
                    # not switch the note id inadvertently.
                    if page.is_closed():
                        stopped_reason = 'Edge 页面关闭'
                        break
                    if now - started_at >= 3:
                        login_visible = bool(page.evaluate(LOGIN_DIALOG_JS))
                        if login_visible:
                            if login_prompt_since is None:
                                login_prompt_since = now
                            elif now - login_prompt_since >= 3:
                                stopped_reason = '网页出现登录/扫码验证；已停止，不自动请求登录'
                                log('检测到登录弹窗，未继续访问；原帖仍可单独使用。')
                                break
                        else:
                            login_prompt_since = None
                    if auto_scroll.is_set() and now >= next_scroll:
                        page.evaluate(SCROLL_JS)
                        next_scroll = now + 1.25
                    if auto_scroll.is_set() and now >= next_reply and reply_button_clicks < 500:
                        # Limit extra clicks per iteration and only click
                        # buttons whose text says to expand replies.
                        candidates = page.get_by_text(re.compile(r'(展开|查看|更多|加载).{0,18}(回复|评论)|(回复|评论).{0,18}(展开|查看|更多|加载)'))
                        n = min(candidates.count(), 15)
                        for i in range(n):
                            item = candidates.nth(i)
                            try:
                                if item.is_visible(timeout=200):
                                    item.click(timeout=500)
                                    reply_button_clicks += 1
                                    break
                            except Exception:
                                continue
                        next_reply = now + 2.2
                except Exception as exc:
                    stopped_reason = '页面停止响应：' + type(exc).__name__
                    break
                if observed['root'] and root_ended_at and not observed_failures:
                    coverage = completeness(list(store.values()), observed, True, '检查中')
                    if (not coverage['reported_reply_gaps']
                            and now - last_page_at >= 5 and now - last_count_at >= 5):
                        auto_end = True
                        stopped_reason = '观察到一级评论分页结束，已知回复数齐全，自动停止'
                        break
                # Limit unproductive run on non-authenticated page. This is
                # not treated as successful completion.
                if now - started_at > 120 and not observed['root'] and now - last_page_at > 120:
                    stopped_reason = '120秒内未获得任何评论分页；可能未登录或页面不提供公开评论'
                    break
            log(f'抓取结束：{len(store)}条；{stopped_reason}')
    except Exception as exc:
        stopped_reason = '浏览器异常：' + f'{type(exc).__name__}: {exc}'
        log(stopped_reason)
    finally:
        if context:
            try:
                context.close()
            except Exception:
                pass
        try:
            coverage = save_result(url, store, observed, auto_end, stopped_reason, logs, Path(target_dir))
            send(('coverage', coverage))
            send(('done', (str(target_dir), '', len(store))))
        except Exception as exc:
            send(('error', '保存评论失败：' + str(exc)))
